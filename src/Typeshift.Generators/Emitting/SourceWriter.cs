using System;
using System.Collections.Generic;
using System.Text;

namespace Typeshift.Generators.Emitting;

internal sealed class SourceWriter
{
    private readonly StringBuilder _builder = new();
    private int _depth;

    public static string Header => "// <auto-generated/>\n#nullable enable\n";

    // What is left of 120 columns at the current indentation
    public int Width => 120 - _depth * 4;

    public SourceWriter Line(string text = "")
    {
        if (text.Length > 0) _builder.Append(' ', _depth * 4).Append(text);

        _builder.Append('\n');
        return this;
    }

    // The lines of a raw string literal, each at the current indentation
    public SourceWriter Lines(string text)
    {
        foreach (var line in text.Split('\n'))
        {
            Line(line.TrimEnd('\r'));
        }

        return this;
    }

    // Comma-separated lines, the last one ending in end instead
    public void List(IReadOnlyList<string> items, string end = "")
    {
        for (var index = 0; index < items.Count; index++)
        {
            Line(items[index] + (index < items.Count - 1 ? "," : end));
        }
    }

    public IDisposable Block(string? header = null, string open = "{", string close = "}")
    {
        if (header is not null) Line(header);

        Line(open);
        _depth++;
        return new Closer(this, close);
    }

    public IDisposable Indent()
    {
        _depth++;
        return new Closer(this, null);
    }

    public override string ToString() => _builder.ToString();

    private sealed class Closer(SourceWriter writer, string? close) : IDisposable
    {
        public void Dispose()
        {
            writer._depth--;
            if (close is not null) writer.Line(close);
        }
    }
}
