    public override void Initialize(AnalysisContext context)
    {
        // The generator reads a file marked <auto-generated/> or named *.g.cs like any other: a toolset a script, a
        // template or another generator wrote. A mistake there is reported there, or the agent that uses the toolset
        // would go without its tools and nobody would hear of it
        context.ConfigureGeneratedCodeAnalysis(
            GeneratedCodeAnalysisFlags.Analyze | GeneratedCodeAnalysisFlags.ReportDiagnostics);
        context.EnableConcurrentExecution();
        context.RegisterCompilationStartAction(Start);
    }

    private static void Start(CompilationStartAnalysisContext context)
    {
        if (context.Compilation.GetTypeByMetadataName(KnownTypes.Toolset) is null) return;

        var tools = new ConcurrentBag<(string Name, INamedTypeSymbol Owner, Location Location)>();
        var kinds = new ConcurrentBag<(string Kind, INamedTypeSymbol Agent)>();
        var found = new Found();

        context.RegisterSymbolStartAction(start => StartClass(start, tools, kinds, found), SymbolKind.NamedType);

        context.RegisterSymbolAction(symbol => CollectJsonTypes(symbol, found), SymbolKind.NamedType);

        var needsJsonMetadata = NeedsJsonMetadata(context.Options.AnalyzerConfigOptionsProvider.GlobalOptions);
        // The library's own builders make the calls a user may not
        if (context.Compilation.AssemblyName != KnownTypes.LibraryAssembly)
        {
            context.RegisterOperationAction(call => AnalyzeCall(call, found), OperationKind.Invocation);
            context.RegisterOperationAction(AnalyzeUnboundTool, OperationKind.Invalid);
        }

        context.RegisterCompilationEndAction(end =>
        {
            ReportLanguageVersion(end, found);
            ReportClashesAcrossToolsets(end, tools);
            ReportUnstampedReferences(end);
            ReportSharedKinds(end, kinds);
            ReportAgentUses(end, found);
            ReportConversationsWithoutDecisions(end, found);
            if (needsJsonMetadata) ReportMissingJsonMetadata(end, found);
            if (needsJsonMetadata) ReportNumericEnums(end, found);
        });
    }

    private static void StartClass(
        SymbolStartAnalysisContext context,
        ConcurrentBag<(string Name, INamedTypeSymbol Owner, Location Location)> tools,
        ConcurrentBag<(string Kind, INamedTypeSymbol Agent)> kinds,
        Found found)
    {
        var type = (INamedTypeSymbol)context.Symbol;
        if (type.IsAbstract) return;

        var baseType = type.DerivesFrom(KnownTypes.Toolset) ? "Toolset"
            : type.DerivesFrom(KnownTypes.Agent) ? "Agent"
            : null;

        if (baseType is null) return;

        found.NeedsGeneratedCode = true;

        var constructors = new ConcurrentBag<IOperation>();

        context.RegisterOperationBlockAction(block =>
        {
            if (block.OwningSymbol is not IMethodSymbol { MethodKind: MethodKind.Constructor }) return;

            foreach (var operation in block.OperationBlocks)
            {
                constructors.Add(operation);
            }
        });

        context.RegisterSymbolEndAction(end =>
        {
            var reporter = new Reporter(end.ReportDiagnostic);
            var ct = end.CancellationToken;

            if (GetIndirection(type, baseType) is { } indirection)
            {
                reporter.Report(
                    Descriptors.NotDirectlyDerived,
                    type.Locations.FirstOrDefault(),
                    type.Name,
                    indirection,
                    $"derive it from {baseType} directly, without type parameters");
                return;
            }

            // D3: the generator finds the class by the name in its base list, and wrote nothing for this one
            if (Discovery.GetAliasedBase(type, baseType, ct) is { } alias)
            {
                reporter.Report(
                    Descriptors.NotDirectlyDerived,
                    alias,
                    type.Name,
                    "names its base through a using alias, which the generator does not follow",
                    $"name {baseType} itself, as in ': {baseType}' or ': Typeshift.{baseType}'");
                return;
            }

            // Constructors come in no particular order; the source order decides which of two clashing
            // declarations is reported, the files by their names in ordinal order, as on every build machine
            var ordered = constructors
                .OrderBy(operation => operation.Syntax.SyntaxTree.FilePath, StringComparer.Ordinal)
                .ThenBy(operation => operation.Syntax.SpanStart)
                .ToList();

            var documented = type.DeclaringSyntaxReferences
                .Any(reference => reference.SyntaxTree.Options.DocumentationMode != DocumentationMode.None);

            var declarations = baseType == "Agent"
                ? ParseAgent(type, ordered, documented, reporter, kinds, found, ct)
                : ParseToolset(type, ordered, documented, reporter, found, ct);

            foreach (var (tool, addTool) in declarations)
            {
                var location = addTool.Syntax.GetLocation();
                found.Tools.Add((tool, location));

                // D57: an agent's own tools clash only across the handoffs of a conversation
                if (baseType == "Agent") found.OwnTools.Add((type, tool.Name, location));
                else tools.Add((tool.Name, type, location));
            }
        });
    }

    private static IReadOnlyList<(ToolModel Tool, IInvocationOperation AddTool)> ParseAgent(
        INamedTypeSymbol type,
        IReadOnlyList<IOperation> constructors,
        bool documented,
        Reporter reporter,
        ConcurrentBag<(string Kind, INamedTypeSymbol Agent)> kinds,
        Found found,
        CancellationToken ct)
    {
        var agent = AgentParser.Parse(
            type,
            constructors,
            documented,
            reporter,
            ct,
            out var uses,
            out var tools,
            out var asks);

        if (agent is null) return tools;

        var toolsetUses = ConstructorChains.GetInvocations(constructors)
            .Where(call => AgentParser.IsDeclaration(call) && call.TargetMethod.Name == "UseToolset")
            .Select(call => (
                call.TargetMethod.TypeArguments[0].ToTypeOf(),
                ConstructorChains.GetCalledName(call).GetLocation()))
            .ToList();

        kinds.Add((agent.Kind, type));
        found.Agents.Add(new FoundAgent(type, agent, uses, asks, toolsetUses));
        return tools;
    }

    private static IReadOnlyList<(ToolModel Tool, IInvocationOperation AddTool)> ParseToolset(
        INamedTypeSymbol type,
        IReadOnlyList<IOperation> constructors,
        bool documented,
        Reporter reporter,
        Found found,
        CancellationToken ct)
    {
        var toolset = ToolsetParser.Parse(type, constructors, documented, reporter, ct, out var tools);
        if (toolset is null) return tools;

        found.Toolsets.Add(Catalog.Summarize(toolset));

        // D2: what the generator read of the toolset is in the stamps of its generated part. Without one there is
        // nothing to compare with yet, as in an editor that has not run the generator since the class was typed
        var stamped = new HashSet<string>(ReferenceReader.GetToolNames(type));

        if (HasGeneratedPart(type) && toolset.Tools.FirstOrDefault(tool => !stamped.Contains(tool.Name)) is { } missing)
        {
            found.Misread[toolset.Type.FullName] = true;

            reporter.Report(
                Descriptors.ReadDifferently,
                type.Locations.FirstOrDefault(),
                type.Name,
                $"the tool '{missing.Name}' is missing");
        }

        return tools;
    }

    private static bool HasGeneratedPart(INamedTypeSymbol type) =>
        type.DeclaringSyntaxReferences.Any(reference => Names.IsGenerated(reference.SyntaxTree));

    private static string? GetIndirection(INamedTypeSymbol type, string baseType) =>
        type switch
        {
            { IsGenericType: true } => "is generic",
            { BaseType: var direct } when !direct.Is($"Typeshift.{baseType}") => $"derives from '{direct!.Name}'",
            _ => null
        };

    private static void AnalyzeCall(OperationAnalysisContext context, Found found)
    {
        var invocation = (IInvocationOperation)context.Operation;
        var target = invocation.TargetMethod;

        // Every call checked here is one of the library's methods, and a project makes few of those among all its
        // calls: comparing the assembly's name costs nothing, each check below a string per call
        if (target.ContainingAssembly?.Name != KnownTypes.LibraryAssembly) return;

        if (InterceptParser.IsIntercepted(target)) found.NeedsGeneratedCode = true;

        // D77: a chat client provider may serve providers of any type, but it must serve some. A type parameter is
        // its caller's to check, since its interfaces are unknown here, and a type that does not resolve the compiler's
        if (target is { Name: "WithChatClientProvider", TypeArguments.Length: 1 }
            && target.ContainingType.Is(KnownTypes.TypeshiftBuilder)
            && target.TypeArguments[0] is { TypeKind: not (TypeKind.TypeParameter or TypeKind.Error) } clients
            && !clients.AllInterfaces.Any(contract => contract.Is(KnownTypes.ChatClientProvider)))
        {
            context.ReportDiagnostic(Diagnostic.Create(
                Descriptors.NoChatClientProvider,
                ConstructorChains.GetCalledName(invocation).GetLocation(),
                clients.Name));

            return;
        }

        // D72: a store of any id type serves the ids of its type; a type parameter is its caller's to check, and a
        // type that does not resolve the compiler's
        if (target is { Name: "WithStore", TypeArguments.Length: 1 }
            && target.ContainingType.Is(KnownTypes.TypeshiftBuilder)
            && target.TypeArguments[0] is { TypeKind: not (TypeKind.TypeParameter or TypeKind.Error) } store)
        {
            var name = ConstructorChains.GetCalledName(invocation).GetLocation();

            if (IsStore(store)) found.Stores.Add(new RegisteredStore(store, name, GetChain(invocation)));
            else context.ReportDiagnostic(Diagnostic.Create(Descriptors.NoStore, name, store.Name));

            return;
        }

        var declares = ToolsetParser.IsAddTool(invocation) || AgentParser.IsDeclaration(invocation);

        if (declares && !IsDirectlyInConstructor(invocation, context.ContainingSymbol))
        {
            context.ReportDiagnostic(Diagnostic.Create(
                Descriptors.OutsideConstructor,
                ConstructorChains.GetCalledName(invocation).GetLocation(),
                target.Name));

            return;
        }

        // D4: a chain call on a variable goes on a chain the generator never sees. A receiver that does not bind, such
        // as the AddTool of an argument the compiler rejects, is the compiler's to report, and a variable that holds
        // a declaration is reported where it is declared
        var receiver = ConstructorChains.Unwrap(invocation.Instance!);

        if (IsChainCall(target)
            && receiver is not (IInvocationOperation or IInvalidOperation)
            && !HoldsDeclaration(receiver, context.CancellationToken))
        {
            context.ReportDiagnostic(Diagnostic.Create(
                Descriptors.UnreadableChain,
                invocation.Syntax.GetLocation(),
                "declaration chain"));
        }
    }

    // var tool = AddTool(Echo): the declaration ends in no statement of its own and is reported for it, as TSH015 in
    // a constructor and as TSH014 outside one, so a call on the variable is the same mistake
    private static bool HoldsDeclaration(IOperation receiver, CancellationToken ct)
    {
        if (receiver is not ILocalReferenceOperation { Local: var local, SemanticModel: { } model }) return false;

        var declared = local.DeclaringSyntaxReferences.FirstOrDefault()?.GetSyntax(ct);
        if (declared is not VariableDeclaratorSyntax { Initializer.Value: var value }) return false;

        var chain = model.GetOperation(value, ct);

        while (chain is not null && ConstructorChains.Unwrap(chain) is IInvocationOperation call)
        {
            if (ToolsetParser.IsAddTool(call) || AgentParser.IsDeclaration(call)) return true;

            chain = call.Instance;
        }

        return false;
    }

    // AddTool(Find) with two methods named Find binds to neither, and the compiler says so as CS1503, "cannot convert
    // from 'method group' to 'System.Delegate'", which names no way out
    private static void AnalyzeUnboundTool(OperationAnalysisContext context)
    {
        var ct = context.CancellationToken;

        if (context.Operation is not
            {
                Syntax: InvocationExpressionSyntax { ArgumentList.Arguments: { Count: 1 } arguments } call,
                SemanticModel: { } model
            }
            || !model.GetSymbolInfo(call, ct).CandidateSymbols.OfType<IMethodSymbol>().Any(ToolsetParser.IsAddTool))
            return;

        var argument = arguments[0].Expression;
        var overloads = model.GetMemberGroup(argument, ct).OfType<IMethodSymbol>().ToList();
        if (overloads.Count < 2) return;

        var first = overloads.OrderBy(method => method.Locations.FirstOrDefault()?.SourceSpan.Start ?? 0).First();
        var cast = GetDelegateType(first, context.Compilation)?.ToMinimalDisplayString(model, argument.SpanStart);
        var pick = cast is null ? "" : $", or pass the one you mean, as in AddTool(({cast}){argument})";

        context.ReportDiagnostic(Diagnostic.Create(
            Descriptors.NotStaticMethodGroup,
            argument.GetLocation(),
            argument.ToString(),
            $"it has {overloads.Count} overloads, and a tool is one method; rename one of them{pick}"));
    }

    // The Func or Action of a method's signature; null for a signature that neither can be closed over
    private static INamedTypeSymbol? GetDelegateType(IMethodSymbol method, Compilation compilation)
    {
        var types = method.Parameters.Select(parameter => parameter.Type).ToList();
        if (!method.ReturnsVoid) types.Add(method.ReturnType);

        var name = method.ReturnsVoid ? "System.Action" : "System.Func";
        var definition = compilation.GetTypeByMetadataName(types.Count == 0 ? name : $"{name}`{types.Count}");

        var closes = method.Parameters.All(parameter => parameter.RefKind == RefKind.None)
            && types.All(type => type is
            {
                IsRefLikeType: false,
                TypeKind: not (TypeKind.Pointer or TypeKind.FunctionPointer)
            });

        return definition is null || !closes ? null
            : types.Count == 0 ? definition
            : definition.Construct([.. types]);
    }

    // D38, D66, D72, D79: a store keeps settings, conversations or decisions, of any id type, or agents' own settings
    private static bool IsStore(ITypeSymbol store) =>
        GetContracts(store).Any(contract => contract.Is(KnownTypes.SettingsStore)
            || contract.Is(KnownTypes.ConversationStore)
            || contract.Is(KnownTypes.DecisionStore)
            || contract.Is(KnownTypes.AgentSettingsStore));

    // A store your code holds as one of the interfaces is that interface too
    private static IEnumerable<INamedTypeSymbol> GetContracts(ITypeSymbol store) =>
        store is INamedTypeSymbol { TypeKind: TypeKind.Interface } contract
            ? [contract, .. store.AllInterfaces]
            : store.AllInterfaces;

    // The chain a builder call belongs to: where its first call stands, or the variable that holds the builder
    private static Location? GetChain(IInvocationOperation invocation)
    {
        var start = invocation.Instance;

        while (start is IInvocationOperation { Instance: { } earlier }) start = earlier;

        return start switch
        {
            ILocalReferenceOperation { Local: var local } => local.Locations.FirstOrDefault(),
            IParameterReferenceOperation { Parameter: var parameter } => parameter.Locations.FirstOrDefault(),
            IFieldReferenceOperation { Field: var field } => field.Locations.FirstOrDefault(),
            IPropertyReferenceOperation { Property: var property } => property.Locations.FirstOrDefault(),
            _ => start?.Syntax.GetLocation()
        };
    }

    // D79: a store of conversations whose chain registers no store of their decisions loads none and fails the
    // first run that asks, which is known here when an agent the project sees can ask
    private static void ReportConversationsWithoutDecisions(CompilationAnalysisContext context, Found found)
    {
        var asking = new System.Lazy<string?>(() => GetAskingAgent(context, found));

        foreach (var chain in found.Stores.GroupBy(store => store.Chain))
        {
            var decided = new HashSet<ITypeSymbol>(
                chain.SelectMany(store => GetIds(store.Type, KnownTypes.DecisionStore)),
                SymbolEqualityComparer.Default);

            var open = chain
                .OrderBy(store => store.Name.SourceSpan.Start)
                .SelectMany(store => GetIds(store.Type, KnownTypes.ConversationStore).Select(id => (store, id)))
                .Where(kept => !decided.Contains(kept.id));

            foreach (var (store, id) in open)
            {
                if (asking.Value is not { } agent) return;

                context.ReportDiagnostic(Diagnostic.Create(
                    Descriptors.ConversationsWithoutDecisions,
                    store.Name,
                    store.Type.Name,
                    id.ToDisplayString(SymbolDisplayFormat.MinimallyQualifiedFormat),
                    agent));
            }
        }
    }

    private static IEnumerable<ITypeSymbol> GetIds(ITypeSymbol store, string contract) =>
        GetContracts(store)
            .Where(implemented => implemented.Is(contract))
            .Select(implemented => implemented.TypeArguments[0]);

    // An agent that can ask your app, of this compilation or of a reference, as far as its declarations and its
    // module stamp say: a tool or an MCP server that requires approval, plan mode, or UseQuestions()
    private static string? GetAskingAgent(CompilationAnalysisContext context, Found found)
    {
        List<ToolsetSummary> toolsets =
        [
            .. found.Toolsets,
            .. ReferenceReader.Read(context.Compilation, context.CancellationToken).Toolsets
        ];

        var own = found.Agents
            .Where(agent => agent.Model.AsksUser
                || agent.Asks.ServersAsk
                || agent.Asks.Plans
                || agent.Asks.ModePick is not null
                || Catalog.Summarize(Catalog.Resolve(agent.Model, toolsets)).ApprovalTools.Count > 0)
            .Select(agent => agent.Type.Name);

        // A stamp names its agent's type in full, from global:: on
        var referenced = ReferenceReader.GetAgents(context.Compilation)
            .Where(agent => agent.AsksUser || agent.ApprovalTools.Count > 0)
            .Select(agent => agent.Type.Substring(agent.Type.LastIndexOfAny(['.', ':']) + 1));

        return own.OrderBy(name => name, System.StringComparer.Ordinal)
            .Concat(referenced.OrderBy(name => name, System.StringComparer.Ordinal))
            .FirstOrDefault();
    }

    private static readonly string[] Builders =
    [
        KnownTypes.ToolBuilder,
        KnownTypes.SettingsBuilder,
        KnownTypes.ConfigurableSettingsBuilder,
        KnownTypes.ToolsetUse,
        KnownTypes.ToolInclusion,
        KnownTypes.ToolExclusion,
        KnownTypes.ChatOptionsBuilder,
        KnownTypes.RunOptionsBuilder
    ];

    private static bool IsChainCall(IMethodSymbol target) =>
        !target.IsStatic && Builders.Any(builder => target.ContainingType.Is(builder));

    private static bool IsDirectlyInConstructor(IOperation operation, ISymbol containing)
    {
        for (var current = operation.Parent; current is not null; current = current.Parent)
        {
            if (current is IAnonymousFunctionOperation or ILocalFunctionOperation) return false;
        }

        return containing is IMethodSymbol { MethodKind: MethodKind.Constructor };
    }

    // D13: a toolset's tool name is unique across everything the host sees, the tools the references stamp too;
    // within one toolset or agent the parser reports it
    private static void ReportClashesAcrossToolsets(
        CompilationAnalysisContext context,
        IEnumerable<(string Name, INamedTypeSymbol Owner, Location Location)> tools)
    {
        const string rule = "tool names are unique across the toolsets of a project and its references; give one of "
            + "the two another name with WithName(\"...\")";

        // A referenced toolset is named in full and with its assembly, which is all there is to search for
        var referenced = ReferenceReader
            .ReadToolsets(context.Compilation, context.CancellationToken)
            .SelectMany(read => read.Toolset.Tools.Select(tool => (
                tool.Name,
                Owner: $"'{read.Toolset.Type.Replace("global::", "")}' in the assembly '{read.Assembly}'")))
            .ToLookup(tool => Names.ToPascalCase(tool.Name));

        foreach (var group in referenced)
        {
            var first = group.First();

            foreach (var clash in group.Skip(1))
            {
                // A referenced tool has no location, so a clash between two references goes on the compilation
                context.ReportDiagnostic(Diagnostic.Create(
                    Descriptors.DuplicateToolName,
                    Location.None,
                    clash.Name,
                    clash.Owner,
                    Meets(clash.Name, first.Name, first.Owner),
                    rule));
            }
        }

        var ordered = tools
            .OrderBy(tool => tool.Location.SourceTree?.FilePath, StringComparer.Ordinal)
            .ThenBy(tool => tool.Location.SourceSpan.Start);

        foreach (var group in ordered.GroupBy(tool => Names.ToPascalCase(tool.Name)))
        {
            var first = group.First();
            var reference = referenced[group.Key].FirstOrDefault();

            var clashes = reference.Name is not null
                ? group
                : group.Skip(1).Where(tool => !SymbolEqualityComparer.Default.Equals(tool.Owner, first.Owner));

            foreach (var clash in clashes)
            {
                var meets = reference.Name is not null
                    ? Meets(clash.Name, reference.Name, reference.Owner)
                    : Meets(clash.Name, first.Name, $"'{first.Owner.Name}'");

                Location[] other = reference.Name is not null ? [] : [first.Location];

                context.ReportDiagnostic(Diagnostic.Create(
                    Descriptors.DuplicateToolName,
                    clash.Location,
                    other,
                    clash.Name,
                    $"'{clash.Owner.Name}'",
                    meets,
                    rule));
            }
        }
    }

    // What a tool name has in common with another tool's: the name itself, or the generated member both map to, as
    // get_v2 and get_v_2 do
    private static string Meets(string name, string other, string otherOwner) =>
        name == other
            ? $"is already declared by {otherOwner}"
            : $"maps to the same generated member as '{other}' of {otherOwner}, '{Names.ToPascalCase(name)}'";

    // D12: the generator writes nothing for a project below C# 14, where its code would be an error per generated
    // member; one diagnostic says what to change, in a project that has something to generate for
    private static void ReportLanguageVersion(CompilationAnalysisContext context, Found found)
    {
        if (!found.NeedsGeneratedCode) return;

        if (context.Compilation is not CSharpCompilation
            {
                LanguageVersion: < TypeshiftGenerator.MinimumLanguageVersion and var version
            })
            return;

        context.ReportDiagnostic(
            Diagnostic.Create(Descriptors.LanguageVersionTooLow, Location.None, version.ToDisplayString()));
    }

    // D9: a reference whose toolsets and agents AddTypeshift() cannot register
    private static void ReportUnstampedReferences(CompilationAnalysisContext context)
    {
        foreach (var assembly in ReferenceReader.GetUnstamped(context.Compilation, context.CancellationToken))
        {
            context.ReportDiagnostic(Diagnostic.Create(
                Descriptors.UnstampedReference,
                Location.None,
                assembly.Name,
                "was built with another Typeshift version or without the Typeshift package",
                "reference the Typeshift package in its project, at this version, and build it again"));
        }

        foreach (var assembly in ReferenceReader.GetUnderAliasOnly(context.Compilation))
        {
            context.ReportDiagnostic(Diagnostic.Create(
                Descriptors.UnstampedReference,
                Location.None,
                assembly.Name,
                "is referenced under an extern alias only, which generated code cannot name",
                "reference it without an alias"));
        }
    }

    // D39: the kinds of this compilation's agents, and those its references stamp
    private static void ReportSharedKinds(
        CompilationAnalysisContext context,
        IEnumerable<(string Kind, INamedTypeSymbol Agent)> kinds)
    {
        // A referenced agent has no location here, so a clash between two references is reported on the compilation
        var referenced = ReferenceReader
            .GetAgentKinds(context.Compilation)
            .Select(stamped => (stamped.Kind, stamped.Agent, Location: Location.None));

        var own = kinds
            .Select(kind => (kind.Kind, Agent: kind.Agent.ToDisplayString(), Location: kind.Agent.Locations.First()))
            .OrderBy(kind => kind.Location.SourceTree?.FilePath, StringComparer.Ordinal)
            .ThenBy(kind => kind.Location.SourceSpan.Start);

        var taken = new Dictionary<string, string>();

        // References first, so a clash with an agent of this compilation is reported on that agent
        foreach (var (kind, agent, location) in referenced.Concat(own))
        {
            if (taken.TryGetValue(kind, out var other))
            {
                context.ReportDiagnostic(Diagnostic.Create(Descriptors.SharedKind, location, agent, kind, other));
                continue;
            }

            taken[kind] = agent;
        }
    }

    // D33, D34: the agents an agent uses, of this compilation or of a reference, whose module stamps them
    private static void ReportAgentUses(CompilationAnalysisContext context, Found found)
    {
        var agents = found.Agents.ToDictionary(
            agent => agent.Type,
            agent => agent,
            (IEqualityComparer<INamedTypeSymbol>)SymbolEqualityComparer.Default);

        List<ToolsetSummary> toolsets =
        [
            .. found.Toolsets,
            .. ReferenceReader.Read(context.Compilation, context.CancellationToken).Toolsets
        ];

        var referenced = ReferenceReader
            .GetAgents(context.Compilation)
            .ToLookup(agent => agent.Type);

        List<(INamedTypeSymbol Agent, string Name, Location Location)> ownTools = [.. found.OwnTools];

        foreach (var (type, _, uses, _, _) in found.Agents)
        {
            foreach (var use in uses)
            {
                if (ResolveTarget(use.Target) is not { } target) continue;

                var role = use.SubAgent ? "a sub-agent" : "a handoff target";

                if (GetUnusableReason(target, use.SubAgent) is { } reason)
                {
                    Report(context, Descriptors.NotUsableAgent, use, use.Target.Name, role, reason);
                }

                if (!use.SubAgent) continue;

                if (target.ApprovalTools.Count > 0)
                {
                    var names = string.Join(", ", target.ApprovalTools);
                    Report(context, Descriptors.SubAgentNeedsApproval, use, use.Target.Name, names);
                }

                // D82: a sub-agent has no conversation to wait in, so it is never offered ask_user
                if (target.AsksUser) Report(context, Descriptors.SubAgentAsksUser, use, use.Target.Name);

                // Assemblies cannot reference each other in a circle, so only this compilation's agents can close one
                if (Calls(use.Target, type, agents))
                {
                    Report(context, Descriptors.AgentCircle, use, type.Name, use.Target.Name);
                }
            }

            ReportNamesOfferedTwice(context, agents[type], toolsets, ownTools, ResolveTarget);
            ReportConfigurableMode(context, agents[type], toolsets);
        }

        ReportClashesAcrossHandoffs(context, agents, toolsets, ResolveTarget, ownTools);
        ReportAgentsReadDifferently(context, found, toolsets);

        ModuleAgent? ResolveTarget(INamedTypeSymbol agent) =>
            agents.TryGetValue(agent, out var own)
                ? Catalog.Summarize(Catalog.Resolve(own.Model, toolsets))
                : referenced[agent.ToTypeOf()].FirstOrDefault();
    }

    // D2: what the generator read of an agent is in the stamp its module carries. An agent without a stamp has no
    // generated part yet, or is out of the module's reach (TSH016). A tool that a toolset already misses is reported
    // there, once, and not on every agent that uses the toolset
    private static void ReportAgentsReadDifferently(
        CompilationAnalysisContext context,
        Found found,
        IReadOnlyList<ToolsetSummary> toolsets)
    {
        var stamps = ReferenceReader.GetOwnAgents(context.Compilation).ToLookup(agent => agent.Type);

        foreach (var agent in found.Agents)
        {
            if (stamps[agent.Type.ToTypeOf()].FirstOrDefault() is not { } stamp) continue;

            var output = Catalog.Resolve(agent.Model, toolsets);
            var read = Catalog.Summarize(output);

            var missing = output.Tools
                .Where(offered => !found.Misread.ContainsKey(offered.Owner))
                .Select(offered => offered.Tool.Name)
                .FirstOrDefault(name => !stamp.Tools.Contains(name));

            var difference = stamp.Name != read.Name ? $"its name is '{stamp.Name}'"
                : stamp.Kind != read.Kind ? $"its kind is '{stamp.Kind}'"
                : stamp.Described != read.Described ? "its description is missing"
                : missing is not null ? $"the tool '{missing}' is missing"
                : null;

            if (difference is null) continue;

            context.ReportDiagnostic(Diagnostic.Create(
                Descriptors.ReadDifferently,
                agent.Type.Locations.FirstOrDefault(),
                agent.Type.Name,
                difference));
        }
    }

    // Null for an agent that can be a tool or a handoff target. A sub-agent's tool has the agent's name, which is
    // none of those a run offers itself (D82)
    private static string? GetUnusableReason(ModuleAgent agent, bool subAgent) =>
        agent switch
        {
            { Described: false } => "it has no description, neither from WithDescription nor from a <summary>",
            _ when !ToolNames.IsLowerSnakeCase(agent.Name) => $"its name '{agent.Name}' is not lower_snake_case",
            _ when subAgent && ToolNames.GetReservedFor(agent.Name) is { } reserved =>
                $"its name '{agent.Name}' is reserved for {reserved}",
            _ => null
        };

    // D37, D57: an agent offers each tool name once, yet two toolsets it uses, of this assembly or a reference, may
    // share one, and so may a toolset and the agent's own tools
    private static void ReportNamesOfferedTwice(
        CompilationAnalysisContext context,
        FoundAgent agent,
        IReadOnlyList<ToolsetSummary> toolsets,
        IReadOnlyList<(INamedTypeSymbol Agent, string Name, Location Location)> ownTools,
        System.Func<INamedTypeSymbol, ModuleAgent?> resolve)
    {
        // Each name with the toolset that offers it, or null for a tool of the agent's own, which comes last (D57)
        var tools = agent.Model.Toolsets
            .SelectMany(use => toolsets.Where(toolset => toolset.Type == use.Toolset)
                .Take(1)
                .SelectMany(toolset => Catalog.Offered(use, toolset)
                    .Select(tool => (tool.Name, Toolset: (string?)toolset.Type))))
            .Concat(agent.Model.Tools.Select(tool => (tool.Name, Toolset: (string?)null)))
            .ToList();

        // The declaration that brings a name a second time is the one reported, and the one to change
        foreach (var name in tools.GroupBy(tool => tool.Name).Where(group => group.Count() > 1))
        {
            var first = Simple(name.First().Toolset!);

            foreach (var (_, toolset) in name.Skip(1))
            {
                var location = toolset is null
                    ? ownTools.FirstOrDefault(tool => Same(tool.Agent, agent.Type) && tool.Name == name.Key).Location
                    : agent.ToolsetUses.FirstOrDefault(use => use.Toolset == toolset).Location;

                context.ReportDiagnostic(Diagnostic.Create(
                    Descriptors.OfferedTwice,
                    location ?? agent.Type.Locations.FirstOrDefault(),
                    $"The tool name '{name.Key}'",
                    $"twice, by '{first}' and by {(toolset is null ? "the agent's own tool" : $"'{Simple(toolset)}'")}",
                    toolset is null
                        ? "leave the toolset's tool out with Exclude(...), or rename the agent's tool with "
                        + "WithName(\"...\")"
                        : "give one of the two tools another name with WithName(\"...\")"));
            }
        }

        // D33, D34: a sub-agent is offered as a tool of its name and a handoff target as handoff_to_{name}, beside
        // the agent's tools, so the use that brings a name a second time is the one reported
        var taken = new HashSet<string>(tools.Select(tool => tool.Name));

        foreach (var use in agent.Uses)
        {
            if (resolve(use.Target) is not { } target) continue;

            var name = use.SubAgent ? target.Name : ToolNames.HandoffPrefix + target.Name;
            if (taken.Add(name)) continue;

            context.ReportDiagnostic(Diagnostic.Create(
                Descriptors.OfferedTwice,
                use.Syntax.GetLocation(),
                $"The tool name '{name}'",
                "twice",
                use.SubAgent
                    ? "a sub-agent is offered as a tool of its name, so rename the tool or the agent with "
                    + "WithName(\"...\")"
                    : $"two handoff targets are named '{target.Name}', so rename one of the agents with "
                    + "WithName(\"...\")"));
        }
    }

    // A type as a message names it: TicketTools for global::Demo.TicketTools
    private static string Simple(string type) => type.Substring(type.LastIndexOfAny(['.', ':']) + 1);

    private static bool Same(ISymbol one, ISymbol other) => SymbolEqualityComparer.Default.Equals(one, other);

    // D52: a configurable mode is a member of the agent's Settings, so settings that are stored or posted can name
    // auto mode, in which the agent's tools that require approval run unasked
    private static void ReportConfigurableMode(
        CompilationAnalysisContext context,
        FoundAgent agent,
        IReadOnlyList<ToolsetSummary> toolsets)
    {
        if (agent.Asks.ModePick is not { } pick) return;

        var guarded = Catalog.Summarize(Catalog.Resolve(agent.Model, toolsets)).ApprovalTools.ToList();

        if (agent.Asks.ServersAsk) guarded.Add("the tools of an MCP server");
        if (guarded.Count == 0) return;

        context.ReportDiagnostic(Diagnostic.Create(
            Descriptors.ConfigurableModeBesideApproval,
            pick.GetLocation(),
            agent.Type.Name,
            string.Join(", ", guarded)));
    }

    // D13, D33, D57: a standing approval names its tool and reaches every agent a handoff passes the conversation to
    // and every sub-agent, so an agent's own tool shares no name with a tool of those; agents it never reaches may
    private static void ReportClashesAcrossHandoffs(
        CompilationAnalysisContext context,
        Dictionary<INamedTypeSymbol, FoundAgent> agents,
        IReadOnlyList<ToolsetSummary> toolsets,
        Func<INamedTypeSymbol, ModuleAgent?> resolve,
        IReadOnlyList<(INamedTypeSymbol Agent, string Name, Location Location)> ownTools)
    {
        const string rename = "give one of the two another name with WithName(\"...\")";
        var reported = new HashSet<(Location, string)>();

        foreach (var from in agents.Keys)
        {
            if (resolve(from) is not { } source) continue;

            ReportDropped(from, source);

            foreach (var to in Reaches(from, agents))
            {
                if (resolve(to) is not { } target) continue;

                // A referenced agent's own tool has no location here, so its clash goes on the agent that reaches it
                Report(from, source, to, target, from.Locations.FirstOrDefault());
                Report(to, target, from, source, from.Locations.FirstOrDefault());
            }
        }

        // An own tool named like a tool of the agent's toolsets but for its underscores, which the agent leaves out;
        // the same name is TSH025, and two own tools of one agent the parser reports
        void ReportDropped(INamedTypeSymbol agent, ModuleAgent offered)
        {
            var own = ownTools.Where(tool => Same(tool.Agent, agent)).ToList();

            var dropped = own.Where(tool => !offered.Tools.Contains(tool.Name)
                && own.Count(other => Names.ToPascalCase(other.Name) == Names.ToPascalCase(tool.Name)) == 1);

            foreach (var tool in dropped)
            {
                var kept = Catalog.Resolve(agents[agent].Model, toolsets).Tools
                    .First(other => Names.ToPascalCase(other.Tool.Name) == Names.ToPascalCase(tool.Name));

                var meets = Meets(tool.Name, kept.Tool.Name, $"'{Simple(kept.Owner)}'");

                Add(tool.Location, tool.Name, agent, meets, rename);
            }
        }

        void Report(
            INamedTypeSymbol owner,
            ModuleAgent own,
            INamedTypeSymbol reached,
            ModuleAgent other,
            Location? fallback)
        {
            var otherOwn = new HashSet<string>(other.OwnTools.Select(Names.ToPascalCase));

            foreach (var name in own.OwnTools)
            {
                var taken = other.Tools.FirstOrDefault(tool => Names.ToPascalCase(tool) == Names.ToPascalCase(name));
                if (taken is null) continue;

                var declared = ownTools.FirstOrDefault(tool => Same(tool.Agent, owner) && tool.Name == name);

                // A clash with the other agent's own tool is reported there already, when that agent is this project's
                if (declared.Location is null && otherOwn.Contains(Names.ToPascalCase(name))) continue;

                var meets = name == taken
                    ? $"is also a tool of '{reached.Name}'"
                    : Meets(name, taken, $"'{reached.Name}'");

                Add(
                    declared.Location ?? fallback ?? Location.None,
                    name,
                    owner,
                    meets,
                    $"a standing approval names its tool and reaches both agents; {rename}");
            }
        }

        void Add(Location location, string name, INamedTypeSymbol owner, string meets, string fix)
        {
            if (!reported.Add((location, name))) return;

            context.ReportDiagnostic(
                Diagnostic.Create(Descriptors.DuplicateToolName, location, name, $"'{owner.Name}'", meets, fix));
        }
    }

    // The agents a standing approval of an agent reaches: a handoff passes the conversation on, and a sub-agent runs
    // with its caller's approvals but without a conversation, so it hands off nothing; a referenced agent's own uses
    // are not stamped
    private static IEnumerable<INamedTypeSymbol> Reaches(
        INamedTypeSymbol from,
        Dictionary<INamedTypeSymbol, FoundAgent> agents)
    {
        var reached = new HashSet<INamedTypeSymbol>(SymbolEqualityComparer.Default) { from };
        var handedOff = new HashSet<INamedTypeSymbol>(SymbolEqualityComparer.Default) { from };
        var called = new HashSet<INamedTypeSymbol>(SymbolEqualityComparer.Default);
        var next = new Stack<(INamedTypeSymbol Agent, bool AsSubAgent)>([(from, false)]);

        while (next.Count > 0)
        {
            var (agent, asSubAgent) = next.Pop();
            if (!agents.TryGetValue(agent, out var found)) continue;

            foreach (var use in found.Uses.Where(use => use.SubAgent || !asSubAgent))
            {
                var subAgent = use.SubAgent || asSubAgent;
                if (!(subAgent ? called : handedOff).Add(use.Target)) continue;

                next.Push((use.Target, subAgent));
                if (reached.Add(use.Target)) yield return use.Target;
            }
        }
    }

    // Whether an agent reaches another through sub-agents
    private static bool Calls(
        INamedTypeSymbol from,
        INamedTypeSymbol to,
        Dictionary<INamedTypeSymbol, FoundAgent> agents)
    {
        var seen = new HashSet<INamedTypeSymbol>(SymbolEqualityComparer.Default);
        var next = new Stack<INamedTypeSymbol>([from]);

        while (next.Count > 0)
        {
            var agent = next.Pop();
            if (SymbolEqualityComparer.Default.Equals(agent, to)) return true;
            if (!seen.Add(agent) || !agents.TryGetValue(agent, out var found)) continue;

            foreach (var use in found.Uses.Where(use => use.SubAgent))
            {
                next.Push(use.Target);
            }
        }

        return false;
    }

    private static void Report(
        CompilationAnalysisContext context,
        DiagnosticDescriptor descriptor,
        AgentUseDeclaration use,
        params object[] arguments) =>
        context.ReportDiagnostic(Diagnostic.Create(descriptor, use.Syntax.GetLocation(), arguments));

    // D45: Microsoft.Extensions.AI's own context covers these, without reflection
    private static readonly HashSet<string> CoveredTypes =
    [
        "string", "char", "short", "ushort", "int", "uint", "long", "ulong", "float", "double", "decimal", "bool",
        "global::System.TimeSpan", "global::System.DateTime", "global::System.DateTimeOffset",
        "global::System.Text.Json.JsonElement", "global::System.Text.Json.JsonDocument",
        "global::System.Text.Json.Nodes.JsonNode", "global::System.Text.Json.Nodes.JsonObject",
        "global::System.Text.Json.Nodes.JsonArray", "global::System.Text.Json.Nodes.JsonValue",
        "global::System.Collections.Generic.IEnumerable<string>"
    ];

    // D45: an app published trimmed has JSON reflection off as one published with Native AOT has, and the SDK says
    // so in this switch. PublishTrimmed is no sign of it: Blazor WebAssembly trims and turns reflection back on
    private static bool NeedsJsonMetadata(AnalyzerConfigOptions options) =>
        Is(options, "JsonSerializerIsReflectionEnabledByDefault", "false")
        || new[] { "PublishAot", "IsAotCompatible", "IsTrimmable" }.Any(name => Is(options, name, "true"));

    private static bool Is(AnalyzerConfigOptions options, string property, string expected) =>
        options.TryGetValue($"build_property.{property}", out var value)
        && value.Equals(expected, StringComparison.OrdinalIgnoreCase);

    private static void CollectJsonTypes(SymbolAnalysisContext context, Found found)
    {
        var type = (INamedTypeSymbol)context.Symbol;

        // The contexts the module registers, as the generator finds them
        if (type is { IsAbstract: true } or { IsGenericType: true }
            || !type.BaseType.Is(KnownTypes.JsonSerializerContext)
            || Discovery.GetAliasedBase(type, "JsonSerializerContext", context.CancellationToken) is not null
            || !Discovery.CanRegister(type, context.CancellationToken)) return;

        var listings = type.GetAttributes()
            .Where(attribute => attribute.AttributeClass.Is(KnownTypes.JsonSerializableAttribute))
            .ToList();

        var listed = listings
            .Select(attribute => attribute.ConstructorArguments.FirstOrDefault().Value)
            .OfType<ITypeSymbol>();

        // The declaration that lists the types is the developer's, another may be the JSON generator's
        var written = listings.FirstOrDefault()?.ApplicationSyntaxReference?.SyntaxTree;
        var location = type.Locations.FirstOrDefault(location => location.SourceTree == written) ?? Location.None;
        var names = JsonEnums.AreNames(type);
        var converted = JsonEnums.GetConverted(type);

        foreach (var json in listed)
        {
            var listedType = json.ToTypeOf();
            found.JsonTypes[listedType] = true;

            if (!names && JsonEnums.FindNumeric(json, converted) is { } numeric)
                found.NumericEnums.Add(new NumericEnum(type.Name, location, listedType, numeric.Name));
        }
    }

    // D45: where JSON reflection is off, every type a tool binds or returns needs metadata from a context
    private static void ReportMissingJsonMetadata(CompilationAnalysisContext context, Found found)
    {
        foreach (var (tool, location) in found.Tools)
        {
            foreach (var type in JsonTypesOf(tool))
            {
                if (CoveredTypes.Contains(type) || found.JsonTypes.ContainsKey(type)) continue;

                context.ReportDiagnostic(Diagnostic.Create(Descriptors.NoJsonMetadata, location, type, tool.Name));
            }
        }
    }

    // D45: there the context that lists a tool's type also decides how an enum in it travels, and says so once
    private static void ReportNumericEnums(CompilationAnalysisContext context, Found found)
    {
        var uses = found.Tools
            .SelectMany(tool => JsonTypesOf(tool.Tool).Select(type => (Type: type, Tool: tool.Tool.Name)))
            .ToList();

        var reports = found.NumericEnums
            .SelectMany(listing => uses
                .Where(use => use.Type == listing.Type)
                .Select(use => (Listing: listing, use.Tool)))
            .GroupBy(report => report.Listing.Context);

        foreach (var report in reports)
        {
            var (listing, tool) = report
                .OrderBy(use => use.Tool, System.StringComparer.Ordinal)
                .ThenBy(use => use.Listing.Enum, System.StringComparer.Ordinal)
                .First();

            context.ReportDiagnostic(Diagnostic.Create(
                Descriptors.NumericEnum,
                listing.Location,
                listing.Context,
                listing.Enum,
                tool));
        }
    }

    // The types a tool's JSON goes through: those of the arguments the model fills, and that of its result
    private static IEnumerable<string> JsonTypesOf(ToolModel tool) =>
        tool.Parameters
            .Where(parameter => parameter.Kind == ParameterKind.Argument)
            .Select(parameter => parameter.TypeOf)
            .Concat(tool.Result is { } result ? [result] : [])
            .Distinct();

